from __future__ import annotations


def format_int(value: int) -> str:
    """Format integer with space as thousands separator (Section 6.1: 1 024)."""
    return f"{int(value):,}".replace(",", " ")


def format_float(value: float, decimals: int = 1) -> str:
    """Format float with decimal comma and space thousands separator (Section 6.1: 87,5)."""
    formatted = f"{value:,.{decimals}f}"
    return formatted.replace(",", " ").replace(".", ",")


def format_pct(value: float, decimals: int = 1) -> str:
    """Format percentage with decimal comma (Section 6.1: 87,5 %)."""
    return f"{format_float(value, decimals)} %"


