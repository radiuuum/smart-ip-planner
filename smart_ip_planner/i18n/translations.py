def get_translator(lang: str = "kk"):
    """Return a lookup function t(key) -> localized string."""
    code = lang if lang in TRANSLATIONS else "kk"
    table = TRANSLATIONS[code]

    def t(key: str) -> str:
        return table.get(key, TRANSLATIONS["kk"].get(key, key))

    return t


def format_finding(finding: DiagnosticFinding, lang: str = "kk") -> tuple[str, str, str]:
    """Return localized (title, message, recommendation) for a DiagnosticFinding."""
    t = get_translator(lang)
    title = t(finding.title_key)
    msg_template = t(finding.message_key)
    try:
        message = msg_template.format(**finding.params)
    except (KeyError, ValueError):
        message = msg_template
    recommendation = t(finding.recommendation_key)
    return title, message, recommendation
